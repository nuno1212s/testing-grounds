#!/usr/bin/env python3
"""Write the uniform-RTT WAN profiles the suite sweeps (bench/wan-profiles/uniform-rtt-*.yml).

Every replica pair gets the same RTT (one region per replica); clients are 0.4 ms from every
replica. No jitter (netem reorders under it) or loss. Output is deterministic; commit it.

Usage:  ./gen_wan_profiles.py [RTT_MS ...]"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lib import wan  # noqa: E402

PROFILE_DIR = os.path.normpath(
    os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "bench", "wan-profiles"))

N_REGIONS = 4  # the suite's cluster is 4 replicas (f = 1)
CLIENT_LINK_RTT_MS = 0.4


def render(rtt_ms):
    links = []
    for a in range(N_REGIONS):
        for b in range(a + 1, N_REGIONS):
            links.append(f"  - {{ a: r{a}, b: r{b}, rtt_ms: {rtt_ms:g} }}")

    placement = "\n".join(f'  "replica-{i}": r{i}' for i in range(N_REGIONS))

    return f"""# {wan.profile_name(rtt_ms)} -- GENERATED by crud_perf/suite/gen_wan_profiles.py; do not edit.
#
# Every replica pair is {rtt_ms:g} ms round-trip ({rtt_ms / 2:g} ms each way). Each replica sits in its
# own region so no pair gets the intra-region default. Clients are {CLIENT_LINK_RTT_MS:g} ms from every replica.
# No jitter, no loss, no bandwidth cap.

defaults:
  rtt_ms: 0
  jitter_ms: 0
  loss_pct: 0
  rate: 10gbit

placement:
{placement}
  "client-*": clients

intra_region:
  rtt_ms: {CLIENT_LINK_RTT_MS:g}

links:
{chr(10).join(links)}

overrides:
  - {{ between: ["client-*", "replica-*"], rtt_ms: {CLIENT_LINK_RTT_MS:g} }}

schedule: []
"""


def main(argv):
    levels = [float(a) for a in argv] or wan.DEFAULT_LEVELS_MS
    os.makedirs(PROFILE_DIR, exist_ok=True)
    for rtt in levels:
        path = os.path.join(PROFILE_DIR, wan.profile_name(rtt) + ".yml")
        with open(path, "w") as f:
            f.write(render(rtt))
        print(f"wrote {os.path.relpath(path)}")


if __name__ == "__main__":
    main(sys.argv[1:])
